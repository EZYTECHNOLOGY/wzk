export function say(lang: Lang, message: string) {
  if (lang === "en" || !message) return message;
  if (heErrors[message]) return heErrors[message];
  if (message.startsWith("Sign in as ")) return `נכנסים כ־${message.slice("Sign in as ".length)} כדי לאשר.`;
  return message;
}

